"""RFC 143 stage 2 part D negative self-tests for
scripts/check-openssl-src-freshness.py.

Run as: python3.14 -m unittest scripts.tests.test_check_openssl_src_freshness
"""

from __future__ import annotations

import importlib.util
import tempfile
import unittest
import urllib.error
from pathlib import Path
from unittest import mock

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SCRIPT_PATH = REPO_ROOT / "scripts" / "check-openssl-src-freshness.py"

spec = importlib.util.spec_from_file_location("check_openssl_src_freshness", SCRIPT_PATH)
cof = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cof)  # type: ignore[union-attr]


def lockfile_text(openssl_src_version: str) -> str:
    return (
        "# This file is automatically @generated by Cargo.\n"
        "version = 4\n\n"
        "[[package]]\n"
        'name = "openssl-src"\n'
        f'version = "{openssl_src_version}"\n'
        "source = \"registry+https://github.com/rust-lang/crates.io-index\"\n"
        'checksum = "deadbeef"\n'
        "dependencies = [\n"
        ' "cc",\n'
        "]\n"
    )


class ParsedVersionTests(unittest.TestCase):
    def test_parses_crate_and_openssl_components(self) -> None:
        v = cof.ParsedVersion("300.6.1+3.6.3")
        self.assertEqual(v.crate, (300, 6, 1))
        self.assertEqual(v.openssl, (3, 6, 3))
        self.assertEqual(v.series(), (3, 6))

    def test_rejects_a_version_with_no_plus_suffix(self) -> None:
        with self.assertRaises(ValueError):
            cof.ParsedVersion("300.6.1")

    def test_two_crate_releases_can_share_one_openssl_patch(self) -> None:
        # Measured on crates.io: 300.5.3+3.5.4 and 300.5.4+3.5.4 are two
        # different crate releases carrying the identical OpenSSL patch --
        # confirms series/newest-patch must compare `.openssl`, never
        # `.crate`.
        a = cof.ParsedVersion("300.5.3+3.5.4")
        b = cof.ParsedVersion("300.5.4+3.5.4")
        self.assertEqual(a.openssl, b.openssl)
        self.assertNotEqual(a.crate, b.crate)


class EvaluateTests(unittest.TestCase):
    def test_current_when_locked_is_the_newest_in_its_series(self) -> None:
        locked = cof.ParsedVersion("300.6.1+3.6.3")
        published = cof.parse_all(["300.6.1+3.6.3", "300.6.0+3.6.2", "300.5.5+3.5.5"])
        result = cof.evaluate(locked, published)
        self.assertFalse(result.behind)
        self.assertFalse(result.newer_series_exists)

    def test_behind_when_a_newer_patch_in_the_same_series_is_published(self) -> None:
        locked = cof.ParsedVersion("300.6.0+3.6.2")
        published = cof.parse_all(["300.6.1+3.6.3", "300.6.0+3.6.2"])
        result = cof.evaluate(locked, published)
        self.assertTrue(result.behind)
        self.assertEqual(result.newest_in_series.openssl, (3, 6, 3))  # type: ignore[union-attr]

    def test_ahead_of_every_published_version_is_not_behind(self) -> None:
        # A patched version this project has already locked that has not
        # yet shown up in a registry listing this check happened to read
        # (propagation lag) must not be reported as behind itself.
        locked = cof.ParsedVersion("300.6.2+3.6.4")
        published = cof.parse_all(["300.6.1+3.6.3", "300.6.0+3.6.2"])
        result = cof.evaluate(locked, published)
        self.assertFalse(result.behind)

    def test_a_series_change_with_no_newer_patch_in_the_locked_series_is_not_behind(
        self,
    ) -> None:
        # The locked series (3.5) has nothing newer published, but a
        # *different*, newer series (3.6) exists. Not behind -- a series
        # change is reported informationally, never auto-failed.
        locked = cof.ParsedVersion("300.5.5+3.5.5")
        published = cof.parse_all(["300.6.1+3.6.3", "300.6.0+3.6.2", "300.5.5+3.5.5"])
        result = cof.evaluate(locked, published)
        self.assertFalse(result.behind)
        self.assertTrue(result.newer_series_exists)

    def test_an_unparseable_published_version_is_skipped_not_fatal(self) -> None:
        published = cof.parse_all(["not-a-version", "300.6.1+3.6.3"])
        self.assertEqual(len(published), 1)
        self.assertEqual(published[0].openssl, (3, 6, 3))


class MainTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def write_lock(self, openssl_src_version: str) -> None:
        (self.root / "Cargo.lock").write_text(lockfile_text(openssl_src_version))

    def test_current_is_exit_zero(self) -> None:
        self.write_lock("300.6.1+3.6.3")
        with mock.patch.object(
            cof, "registry_versions", return_value=["300.6.1+3.6.3", "300.6.0+3.6.2"]
        ):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 0)

    def test_behind_is_exit_one(self) -> None:
        self.write_lock("300.6.0+3.6.2")
        with mock.patch.object(
            cof, "registry_versions", return_value=["300.6.1+3.6.3", "300.6.0+3.6.2"]
        ):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 1)

    def test_ahead_is_exit_zero(self) -> None:
        self.write_lock("300.6.2+3.6.4")
        with mock.patch.object(
            cof, "registry_versions", return_value=["300.6.1+3.6.3", "300.6.0+3.6.2"]
        ):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 0)

    def test_a_series_change_with_the_locked_series_current_is_exit_zero(self) -> None:
        self.write_lock("300.5.5+3.5.5")
        with mock.patch.object(
            cof,
            "registry_versions",
            return_value=["300.6.1+3.6.3", "300.6.0+3.6.2", "300.5.5+3.5.5"],
        ):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 0)

    def test_a_missing_lockfile_is_exit_two(self) -> None:
        rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 2)

    def test_a_lockfile_with_no_openssl_src_package_is_exit_two(self) -> None:
        (self.root / "Cargo.lock").write_text("# This file is automatically @generated.\n")
        rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 2)

    def test_a_registry_error_is_exit_two(self) -> None:
        self.write_lock("300.6.1+3.6.3")
        with mock.patch.object(
            cof, "registry_versions", side_effect=urllib.error.URLError("boom")
        ):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 2)

    def test_an_empty_registry_response_is_exit_two(self) -> None:
        self.write_lock("300.6.1+3.6.3")
        with mock.patch.object(cof, "registry_versions", return_value=[]):
            rc = cof.main(["--root", str(self.root)])
        self.assertEqual(rc, 2)


if __name__ == "__main__":
    unittest.main()
